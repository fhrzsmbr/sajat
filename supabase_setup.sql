create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 20),
  score integer not null check (score >= 0 and score <= 1000000),
  created_at timestamptz not null default now()
);

create index if not exists scores_score_created_at_idx
on public.scores (score desc, created_at asc);

alter table public.scores enable row level security;

-- Bárki megtekintheti a globális Top 10 ranglistához szükséges adatokat.
create policy "Scores are publicly readable"
on public.scores
for select
to anon, authenticated
using (true);

-- Bejelentkezés nélkül is beküldhető egy eredmény.
create policy "Anyone can submit a score"
on public.scores
for insert
to anon, authenticated
with check (
  char_length(player_name) between 1 and 20
  and score >= 0
  and score <= 1000000
);
